const BRACKET_RE = /\[[^\]]+\]/g;

function normalizeTurn(turn) {
  const out = { ...turn };
  delete out.seq;
  if (out.asr === null) delete out.asr;
  if (BRACKET_RE.test(turn.text || '')) {
    const parts = [...String(turn.text).matchAll(BRACKET_RE)].map((m) => m[0].slice(1, -1));
    out.stage_direction = parts.join('; ');
    out.text = String(turn.text).replace(BRACKET_RE, '').replace(/\s+/g, ' ').trim();
    if (!out.text) out.text = '(pause)';
  }
  return out;
}

